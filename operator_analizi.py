# 1. Aşama: Aritmetik Operatörlerin İncelenmesi
normal_bolme = 10 / 4
taban_bolme = 10 // 4
kalan_bulma = 10 % 4
print("Normal Bölme Sonucu:", normal_bolme)
print("Taban Bölme Sonucu:", taban_bolme)
print("Bölme İşleminden Kalan:", kalan_bulma)
# 2. Aşama: İlişkisel ve Mantıksal Operatörlerin İncelenmesi
sayi1 = 15
sayi2 = 20
# Çoklu koşul denetimi (and ve or operatörlerinin davranışı)
kosul_ve = (sayi1 > 10) and (sayi2 < 15)
kosul_veya = (sayi1 > 10) or (sayi2 < 15)
kosul_degil = not (sayi1 == sayi2)
print("ve (and) Koşul Çıktısı:", kosul_ve)
print("veya (or) Koşul Çıktısı:", kosul_veya)
print("değil (not) Koşul Çıktısı:", kosul_degil)